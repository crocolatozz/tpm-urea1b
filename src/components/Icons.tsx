const baseIconClass = 'inline-block shrink-0 align-[-0.125em]';

function getIconClass(className = 'w-5 h-5', extraClass = ''): string {
  const trimmed = className.trim();
  const hasExplicitSize = /(?:^|\s)[wh]-/.test(trimmed);
  const sizeClass = hasExplicitSize ? '' : 'w-5 h-5';
  return `${baseIconClass} ${extraClass} ${sizeClass} ${trimmed}`.replace(/\s+/g, ' ').trim();
}

